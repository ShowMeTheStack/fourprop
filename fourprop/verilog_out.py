"""Write a Circuit as plain structural Verilog (one `assign` per gate) for synthesis flows (ORFS/Yosys).

Names are sanitised to legal Verilog identifiers; the mapping is returned so primary inputs/outputs can be matched later.
"""
from __future__ import annotations
import re
from typing import Dict, Tuple
from .circuit import Circuit

_KEYWORDS = {"module", "input", "output", "wire", "assign", "and", "or", "not", "xor", "reg", "begin", "end", "if", "else", "case", "for", "endmodule", "parameter", "inout", "always", "signed"}


def _ident(name: str, used: set) -> str:
    s = re.sub(r"[^A-Za-z0-9_]", "_", name)
    if not s or not re.match(r"[A-Za-z_]", s[0]):
        s = "n_" + s
    if s in _KEYWORDS:
        s = s + "_"
    base = s; i = 1
    while s in used:
        s = f"{base}_{i}"; i += 1
    used.add(s)
    return s


def write_verilog(circ: Circuit, path: str, module: str) -> Dict[str, str]:
    used: set = set(); names: Dict[int, str] = {}
    port_ids = set(circ.inputs) | set(circ.outputs)
    for i, nd in enumerate(circ.nodes):
        # internal nets get a private prefix: benchmark names such as new_n35 collide with ABC's own wire names inside Yosys
        names[i] = _ident(nd.name if i in port_ids else "fp_" + nd.name, used)
    ins = [names[i] for i in circ.inputs]; outs = []
    # an output that is also an input or that would be driven twice gets its own wire
    out_ids = list(dict.fromkeys(circ.outputs))
    lines = [f"// {circ.name}: {circ.n_inputs} inputs, {len(out_ids)} outputs, {circ.n_gates} gates; generated by fourprop", f"module {module} ("]
    port_names = ins + []
    out_names = []
    for i in out_ids:
        nm = names[i]
        if i in circ.inputs:
            nm = _ident(nm + "_out", used)
        out_names.append((i, nm)); port_names.append(nm)
    lines.append("  " + ", ".join(port_names) + ");")
    lines.append("  input " + ", ".join(ins) + ";")
    lines.append("  output " + ", ".join(nm for _, nm in out_names) + ";")
    internal = [names[i] for i, nd in enumerate(circ.nodes) if nd.op != "INPUT" and names[i] not in dict(out_names).values()]
    if internal:
        lines.append("  wire " + ", ".join(internal) + ";")
    for i, nd in enumerate(circ.nodes):
        if nd.op == "INPUT":
            continue
        fan = [names[j] for j in nd.fanins]
        if nd.op == "CONST0":
            expr = "1'b0"
        elif nd.op == "CONST1":
            expr = "1'b1"
        elif nd.op == "BUF":
            expr = fan[0]
        elif nd.op == "NOT":
            expr = "~" + fan[0]
        else:
            opch = {"AND": " & ", "OR": " | ", "XOR": " ^ "}[nd.op]
            expr = "(" + opch.join(fan) + ")"
        if nd.inv:
            expr = "~" + expr
        lines.append(f"  assign {names[i]} = {expr};")
    for i, nm in out_names:
        if nm != names[i]:
            lines.append(f"  assign {nm} = {names[i]};")
    lines.append("endmodule")
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    return {circ.nodes[i].name: names[i] for i in range(len(circ.nodes))}
